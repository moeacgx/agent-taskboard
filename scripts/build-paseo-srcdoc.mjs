import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const output = path.join(root, "integrations", "paseo", ".paseo-web-dist");
const destination = path.join(root, "integrations", "paseo", "client", "original-app.generated.ts");
const [html, css, script] = await Promise.all([
  readFile(path.join(output, "index.html"), "utf8"),
  readFile(path.join(output, "app.css"), "utf8"),
  readFile(path.join(output, "app.js"), "utf8"),
]);

const ASSET_MIME_TYPES = {
  "codex-agent-logo.png": "image/png",
  "codex-app-icon.png": "image/png",
  "favicon.svg": "image/svg+xml",
};

const embeddedAssets = Object.fromEntries(await Promise.all(
  Object.entries(ASSET_MIME_TYPES).map(async ([name, mimeType]) => [
    name,
    `data:${mimeType};base64,${(await readFile(path.join(output, name))).toString("base64")}`,
  ]),
));

/** 将原版构建中仅有的本地静态图像嵌入 srcDoc，避免 sandbox 请求虚构基址。 */
function inlineAssets(value) {
  return Object.entries(embeddedAssets).reduce(
    (current, [name, dataUrl]) => current.replaceAll(`./${name}`, dataUrl).replaceAll(name, dataUrl),
    value,
  );
}

const srcdoc = inlineAssets(html)
  // 必须使用回调：原版压缩 JS 含有 $&、$`、$'，字符串替换会把它们误解为匹配占位符。
  .replace(/<link[^>]+href="\.\/app\.css"[^>]*>/, () => `<style>${inlineAssets(css)}</style>`)
  // Vite 输出仍是 ESM（含 import.meta），内联后也必须保留 module 语义。
  .replace(/<script[^>]+src="\.\/app\.js"[^>]*><\/script>/, () => `<script type="module">${inlineAssets(script).replace(/<\/script/gi, "<\\/script")}</script>`)
  .replace("<head>", '<head><base href="https://paseo-taskboard.invalid/?host=paseo&channel=__PASEO_CHANNEL__&nonce=__PASEO_NONCE__">');

await writeFile(destination, `// Generated by scripts/build-paseo-srcdoc.mjs; do not edit manually.\nexport const ORIGINAL_APP_SRCDOC_TEMPLATE = ${JSON.stringify(srcdoc)};\n`, "utf8");
